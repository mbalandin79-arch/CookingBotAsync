-- ============================================================
-- 04_ReleaseMigration.sql
-- Миграция уже развёрнутой базы "ToDoList" с состояния ДЗ17
-- на РЕЛИЗНОЕ состояние (без пересоздания базы и потери данных).
--
-- Что меняет:
--   1. Роли: Guest (State=0) переводится в Member (State=1);
--   2. Добавляется CHECK на роли 1-4 (как в 01_ToDoListDb.sql);
--   3. Удаляются столбцы рецепта: "Deadline", "State",
--      "StateChangedAt" (дедлайн и статус ушли из релиза).
--
-- ВАЖНО - ПОРЯДОК ПРИМЕНЕНИЯ:
--   Скрипт применять ТОЛЬКО ПОСЛЕ обновления кода бота до
--   релизной версии и остановки бота. Релизный код не читает
--   удаляемые столбцы и роль Guest; старый код (ДЗ17) на новой
--   схеме работать перестанет.
--
-- Повторный запуск скрипта не предусмотрен: ADD CONSTRAINT
-- упадёт с ошибкой "already exists" - это ожидаемо и ничего
-- не ломает (остальные шаги при этом уже выполнены).
--
-- Как запускать (только через psql и только через ФАЙЛ -
-- при запуске через "psql -c" двойные кавычки вокруг имён теряются):
--   "C:\Program Files\PostgreSQL\18\bin\psql.exe" -U postgres -d ToDoList -f 04_ReleaseMigration.sql
--   (пароль спросят интерактивно; запускать из папки со скриптом
--    или указать полный путь к файлу)
-- ============================================================

-- ------------------------------------------------------------
-- 1. Роли: Guest (0) -> Member (1).
-- Выполняется ДО добавления CHECK: иначе CHECK запретит UPDATE.
-- ------------------------------------------------------------
UPDATE "ToDoUser"
SET "State" = 1
WHERE "State" = 0;

-- ------------------------------------------------------------
-- 2. Ограничение ролей: только 1-4 (как в 01_ToDoListDb.sql).
-- Страховка от опечаток в коде и ручных правок в БД.
-- ------------------------------------------------------------
ALTER TABLE "ToDoUser"
    ADD CONSTRAINT "CK_ToDoUser_State" CHECK ("State" BETWEEN 1 AND 4);

-- ------------------------------------------------------------
-- 3. Удаление ушедших столбцов рецепта.
-- Данные в них теряются - в релизе они не используются.
-- IF EXISTS: на чистой базе из 01 столбцов уже нет,
-- шаг просто пропустится (но шаг 2 всё равно упадёт - см. шапку).
-- ------------------------------------------------------------
ALTER TABLE "ToDoItem" DROP COLUMN IF EXISTS "Deadline";
ALTER TABLE "ToDoItem" DROP COLUMN IF EXISTS "State";
ALTER TABLE "ToDoItem" DROP COLUMN IF EXISTS "StateChangedAt";
