-- 04_AlterAddDeadline.sql
-- Добавление столбца "Deadline" в таблицу "ToDoItem" (ДЗ17, п.4).
--
-- Назначение: обновление УЖЕ РАЗВЁРНУТОЙ базы данных "ToDoList"
-- без её пересоздания (00_ReCreateToDoListDb.sql уничтожил бы
-- все данные). Новая база, созданная по 01/00, уже содержит
-- этот столбец — тогда скрипт ничего не меняет (IF NOT EXISTS).
--
-- Как запускать (только через psql и только через ФАЙЛ -
-- при запуске через "psql -c" двойные кавычки вокруг имён теряются):
--   "C:\Program Files\PostgreSQL\18\bin\psql.exe" -U postgres -d ToDoList -f 04_AlterAddDeadline.sql
--   (пароль спросят интерактивно; запускать из папки со скриптом
--    или указать полный путь к файлу)
-- ============================================================

-- Дедлайн рецепта: дата, когда пользователь планирует приготовить блюдо.
-- NULL = дедлайн не задан (у существующих рецептов дедлайна нет).
ALTER TABLE "ToDoItem"
    ADD COLUMN IF NOT EXISTS "Deadline" TIMESTAMPTZ NULL;

COMMENT ON COLUMN "ToDoItem"."Deadline" IS 'Дедлайн рецепта: дата планируемого приготовления (NULL = нет дедлайна)';
